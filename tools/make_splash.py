"""The splash image into the firmware: a 240x240 PNG as a palette of 16 RGB565 colours (no dither) and its indices
packed two to a byte, the left pixel in the high nibble: one C header (app/splash.inc, read by app.c's app_splash).
A noisy picture runs few pixels alike, so packing beats run-length coding: 28,800 bytes, where 256 colours run-length
coded took 60 KB and looked no better on the FM-1's screen. After Amenity's (tools/jungle/make_splash.py).
usage: python -I tools/make_splash.py assets/splash.png app/splash.inc"""
import sys
from PIL import Image

COLOURS = 16


def main(src, dst):
    im = Image.open(src).convert("RGB")
    if im.size != (240, 240):
        sys.exit(f"make_splash: {src} is {im.size[0]}x{im.size[1]}, wants 240x240")
    q = im.quantize(colors=COLOURS, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[: 3 * COLOURS]
    pal += [0] * (3 * COLOURS - len(pal))
    idx = q.tobytes()
    c565 = [((pal[3 * k] >> 3) << 11) | ((pal[3 * k + 1] >> 2) << 5) | (pal[3 * k + 2] >> 3) for k in range(COLOURS)]
    data = bytes((idx[i] << 4) | idx[i + 1] for i in range(0, len(idx), 2))
    with open(dst, "w", newline="\n") as f:
        f.write(f"/* generated by tools/make_splash.py from {src.replace(chr(92), '/').split('/')[-1]}: "
                f"{COLOURS} colours, 4 bits a pixel */\n")
        f.write(f"static const uint16_t SPLASH_PAL[{COLOURS}] = {{")
        f.write(",".join(f"0x{c:04X}" for c in c565) + "};\n")
        f.write(f"static const uint8_t SPLASH_4BPP[{len(data)}] = {{\n")
        for k in range(0, len(data), 24):
            f.write("    " + ",".join(str(b) for b in data[k:k + 24]) + ",\n")
        f.write("};\n")
    print(f"make_splash: {COLOURS} colours, {len(data) + 2 * COLOURS} bytes")


if __name__ == "__main__":
    main(*sys.argv[1:3])
